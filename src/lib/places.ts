export interface MapPoint {
  lat: number;
  lng: number;
  /** True when only the city is known, so the pin sits on the city centre. */
  approximate: boolean;
}

export function mapPointOf(place: { city: string; lat?: number; lng?: number }): MapPoint | null {
  if (place.lat !== undefined && place.lng !== undefined) {
    return { lat: place.lat, lng: place.lng, approximate: false };
  }
  const centre = CITY_COORDS[place.city];
  return centre ? { lat: centre[0], lng: centre[1], approximate: true } : null;
}

export function districtsOf(city: string): readonly string[] {
  return CITY_DISTRICTS[city] ?? [];
}

/** "Žvėrynas, Vilnius" when a district is known, otherwise just "Vilnius". */
export function formatPlace(place: { city: string; district: string }): string {
  return place.district ? `${place.district}, ${place.city}` : place.city;
}
